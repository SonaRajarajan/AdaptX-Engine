export function applyAdSampleToCampaign(currentCampaign: Campaign, preset: AdSamplePreset): Campaign {
  const brandName = preset.name.split(' ')[0];
  const logoUrl = preset.logoUrl || createBrandLogoUrl(brandName, preset.brandColors.primary, preset.brandColors.text);

  return {
    ...currentCampaign,
    id: preset.id,
    name: preset.name,
    assets: {
      ...currentCampaign.assets,
      logoUrl,
      headline: preset.headline,
      headlineCompact: preset.headlineCompact,
      headlineExtreme: preset.headlineExtreme,
      description: preset.bodyDescription,
      descriptionCompact: preset.bodyDescriptionCompact,
      descriptionExtreme: preset.bodyDescriptionExtreme,
      ctaText: preset.ctaText,
      legalText: preset.legalText,
      productImageUrl: preset.productImageUrl,
      focalPoint: preset.focalPoint,
      brandColors: preset.brandColors,
      fontFamily: preset.fontFamily,
      headlineFontSize: preset.headlineFontSize || currentCampaign.assets.headlineFontSize,
      ctaFontSize: preset.ctaFontSize || currentCampaign.assets.ctaFontSize,
      headlineColor: preset.headlineColor || preset.brandColors.primary,
      ctaTextColor: preset.ctaTextColor || preset.brandColors.text,
    },
    constraints: {
      ...currentCampaign.constraints,
      ctaStyle: preset.ctaStyle,
      fontFamily: preset.fontFamily,
      allowedBrandColors: [
        preset.brandColors.primary,
        preset.brandColors.secondary,
        preset.brandColors.background,
        preset.brandColors.accent,
      ],
    },
  };
}
