export function createBrandLogoUrl(brandName: string, primaryColor: string = '#EAB308', textColor: string = '#000000'): string {
  const text = brandName.toUpperCase();
  const width = Math.max(90, text.length * 14 + 28);
  const bgCol = primaryColor.startsWith('#') ? primaryColor.replace('#', '%23') : primaryColor;
  const txtCol = textColor.startsWith('#') ? textColor.replace('#', '%23') : textColor;
  return `data:image/svg+xml;utf8,<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="40" viewBox="0 0 ${width} 40"><rect width="${width}" height="40" rx="6" fill="${bgCol}" stroke="%23000000" stroke-width="3"/><text x="14" y="26" font-family="sans-serif" font-weight="900" font-size="17" fill="${txtCol}">${text}</text></svg>`;
}

